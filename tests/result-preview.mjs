import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM} from 'jsdom';
const dom=new JSDOM('<main id="app"></main>',{runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window, app=w.document.querySelector('#app');
let reduced=false, now=0, cancelled=0, revealed=0;
w.matchMedia=()=>({matches:reduced});
Object.defineProperty(w.performance,'now',{value:()=>now});
w.HTMLElement.prototype.animate=()=>({cancel(){cancelled++;}});
w.CONTINUUM={UI:{mount(){},openSurface(){},reveal(){revealed++;}}};
w.eval(fs.readFileSync(new URL('../a11y.js',import.meta.url),'utf8'));
const html=id=>`<div class="timeline-wrap"><article class="timeline-card" data-id="${id}"></article></div><div class="overlay" data-result-card="${id}"><div class="modal"><h2>Acierto</h2><button data-dialog-focus>Continuar</button></div></div>`;
const open=id=>{w.CONTINUUM.paint(app,html(id),'online-game');const el=app.querySelector('.overlay');w.CONTINUUM.openDialog(el,false);return el;};
const first=open('67');
assert.ok(first.classList.contains('result-preview'));
assert.equal(revealed,0,'el revelado no comienza detrás de la capa oculta');
assert.equal(w.document.activeElement,first);
assert.equal(w.CONTINUUM.backPressed(),true,'Atrás no atraviesa la pausa');
const tab=new w.KeyboardEvent('keydown',{key:'Tab',cancelable:true});w.document.dispatchEvent(tab);assert.ok(tab.defaultPrevented);
now=900;
const repaint=open('67');
assert.equal(cancelled,1,'repintar cancela la animación y el temporizador antiguos');
await new Promise(r=>setTimeout(r,240));
assert.equal(repaint.classList.contains('result-preview'),false,'la instantánea no reinicia los 1100 ms');
assert.equal(revealed,1);
assert.equal(w.document.activeElement,app.querySelector('button'));
assert.equal(app.querySelector('.modal').getAttribute('role'),'dialog');
now=2000;open('68');
w.CONTINUUM.paint(app,'<h1>Inicio</h1>','home');
await new Promise(r=>setTimeout(r,1150));
assert.equal(revealed,1,'salir cancela el resultado pendiente');
assert.equal(w.CONTINUUM.backPressed(),false);
reduced=true;const immediate=open('69');
assert.equal(immediate.classList.contains('result-preview'),false);
assert.equal(revealed,2,'movimiento reducido abre sin esperar');
dom.window.close();
console.log('Resultado: tablero visible, foco, repintado online, cancelación y movimiento reducido OK.');
